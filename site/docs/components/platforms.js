const num = new Intl.NumberFormat("en-US");

function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"]/g, (c) => ({
    "&": "&amp;",
    "<": "&lt;",
    ">": "&gt;",
    '"': "&quot;"
  })[c]);
}

function split(value) {
  return String(value ?? "")
    .split(";")
    .map((part) => part.trim())
    .filter(Boolean);
}

function shorten(value, max = 64) {
  const text = String(value ?? "");
  return text.length > max ? `${text.slice(0, max - 1).trimEnd()}…` : text;
}

function slug(value) {
  return String(value ?? "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function plural(count, singular, pluralForm = `${singular}s`) {
  return count === 1 ? singular : pluralForm;
}

function number(value) {
  return Number(value) || 0;
}

function certNumber(cert) {
  return Number(String(cert ?? "").replace(/\D/g, "")) || 0;
}

function csvCell(value) {
  const text = value === null || value === undefined ? "" : String(value);
  return /[",\n\r]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

/**
 * Render the chipset/platform shortlist.
 *
 * `families` is platform_families.csv; `certs` is
 * platform_family_certs.csv. Both are generated by the scrape. The component
 * filters client-side so the page needs no DuckDB query for this view.
 */
export function platformShortlist({families, certs, unmapped = [], totalEsv}) {
  const definitions = families.map((row) => ({
    ...row,
    id: slug(row.family),
    openPhysical: number(row.open_physical),
    allCount: number(row.esv_certs)
  }));

  const certsByFamily = new Map();
  for (const row of certs) {
    const cert = {
      ...row,
      certNum: certNumber(row.cert),
      environments: split(row.matched_environments),
      strong:
        row.reuse_status === "Open for Reuse" && row.noise_source === "Physical"
    };
    if (!certsByFamily.has(row.family)) certsByFamily.set(row.family, []);
    certsByFamily.get(row.family).push(cert);
  }

  const sortCerts = (a, b) => {
    const score = (row) => (row.strong ? 2 : 0) + (row.reuse_status === "Open for Reuse" ? 1 : 0);
    return score(b) - score(a) || b.certNum - a.certNum;
  };

  const unmappedCerts = unmapped.map((row) => ({
    ...row,
    certNum: certNumber(row.cert),
    environments: split(row.operating_environments),
    strong:
      row.reuse_status === "Open for Reuse" && row.noise_source === "Physical"
  })).sort(sortCerts);

  const platformFamilies = definitions
    .map((definition) => {
      const allCerts = [...(certsByFamily.get(definition.family) ?? [])].sort(sortCerts);
      return {
        ...definition,
        allCerts,
        allCount: allCerts.length
      };
    })
    .filter((family) => family.allCerts.length > 0);

  const strongFamilies = platformFamilies.filter((family) => family.openPhysical > 0).length;
  const strongMatches = platformFamilies.reduce((total, family) => total + family.openPhysical, 0);
  const unmappedCount = unmappedCerts.length;
  const mappedCount = Math.max(0, number(totalEsv) - unmappedCount);
  const categories = [...new Set(platformFamilies.map((family) => family.category))].sort();
  const vendors = [...new Set(
    platformFamilies.flatMap((family) => family.allCerts.map((cert) => cert.vendor).filter(Boolean))
  )].sort((a, b) => a.localeCompare(b, undefined, {sensitivity: "base"}));

  const state = {
    query: "",
    category: "all",
    vendor: "all",
    noise: "Physical",
    reuse: "Open for Reuse",
    fullEntropy: false,
    sortKey: "openPhysical",
    sortDir: -1,
    open: new Set()
  };

  function matchesEntropy(cert) {
    if (state.vendor !== "all" && cert.vendor !== state.vendor) return false;
    if (state.noise !== "all" && cert.noise_source !== state.noise) return false;
    if (state.reuse !== "all" && cert.reuse_status !== state.reuse) return false;
    if (state.fullEntropy && !/full/i.test(cert.bits_per_output || "")) return false;
    return true;
  }

  function familyView(family) {
    const certs = family.allCerts.filter(matchesEntropy);
    if (!certs.length) return null;

    const open = certs.filter((cert) => cert.reuse_status === "Open for Reuse").length;
    const physical = certs.filter((cert) => cert.noise_source === "Physical").length;
    const openPhysical = certs.filter((cert) => cert.strong).length;
    const entropyVendors = [...new Set(certs.map((cert) => cert.vendor).filter(Boolean))];
    const environments = [...new Set(certs.flatMap((cert) => cert.environments))];
    const examples = [...environments]
      .sort((a, b) => a.length - b.length || a.localeCompare(b))
      .slice(0, 3);

    return {
      ...family,
      certs,
      open,
      physical,
      openPhysical,
      entropyVendors,
      environments,
      examples
    };
  }

  function familyMatchesQuery(family, query) {
    if (!query) return true;
    return [
      family.family,
      family.platform_vendor,
      family.category,
      ...family.environments
    ].join("\n").toLowerCase().includes(query);
  }

  function compareFamilies(a, b) {
    let value;
    if (state.sortKey === "name") value = a.family.localeCompare(b.family);
    else if (state.sortKey === "total") value = a.certs.length - b.certs.length;
    else if (state.sortKey === "vendors") value = a.entropyVendors.length - b.entropyVendors.length;
    else value = a.openPhysical - b.openPhysical;

    value *= state.sortDir;
    if (value !== 0) return value;
    return b.openPhysical - a.openPhysical
      || b.certs.length - a.certs.length
      || a.family.localeCompare(b.family);
  }

  function filteredFamilies() {
    const query = state.query.trim().toLowerCase();
    return platformFamilies
      .map(familyView)
      .filter(Boolean)
      .filter((family) => (state.category === "all" || family.category === state.category)
        && familyMatchesQuery(family, query))
      .sort(compareFamilies);
  }

  /* ---------- shell ---------- */

  const root = document.createElement("div");
  root.className = "platforms";
  root.innerHTML = `
    <div class="stats platform-stats"></div>
    <div class="note platform-callout entropy-wide"></div>
    <div class="pf-controls">
      <label class="pf-field pf-search"><span>Search</span>
        <input type="search" placeholder="Family, vendor, or environment…" aria-label="Search chipset families">
      </label>
      <label class="pf-field"><span>Category</span><select class="pf-category"></select></label>
      <label class="pf-field"><span>Entropy vendor</span><select class="pf-vendor-select"></select></label>
      <label class="pf-field"><span>Noise</span>
        <select class="pf-noise">
          <option value="all">Any</option>
          <option value="Physical">Physical</option>
          <option value="Non-Physical">Non-Physical</option>
        </select>
      </label>
      <label class="pf-field"><span>Reuse</span>
        <select class="pf-reuse">
          <option value="all">Any</option>
          <option value="Open for Reuse">Open for Reuse</option>
          <option value="Reuse restricted to vendor">Restricted to vendor</option>
        </select>
      </label>
      <label class="pf-check"><input type="checkbox" class="pf-full"> Full entropy</label>
      <button type="button" class="pf-reset">Reset entropy</button>
      <label class="pf-field pf-sort"><span>Sort</span>
        <select>
          <option value="openPhysical">Open + physical</option>
          <option value="total">Total ESV certificates</option>
          <option value="vendors">Entropy vendors</option>
          <option value="name">Family name</option>
        </select>
      </label>
      <button type="button" class="pf-download">Download filtered CSV</button>
    </div>
    <div class="pf-count small"></div>
    <div class="pf-head" aria-hidden="true">
      <span>Platform family</span>
      <span>Open + physical</span>
      <span>ESV certs</span>
      <span>Entropy vendors</span>
      <span>Example environments</span>
      <span></span>
    </div>
    <div class="pf-list"></div>
    <details class="pf-unmapped" id="unmapped">
      <summary class="pf-unmapped-summary">
        <span class="pf-unmapped-title">Unmapped certificates <span class="pf-unmapped-count"></span></span>
        <span class="pf-unmapped-hint">No configured family matched; inspect these for new platform leads.</span>
      </summary>
      <div class="pf-unmapped-body">
        <p class="pf-unmapped-note">
          These ESV certificates match no family in <code>platform_families.toml</code>.
          They are shown here rather than hidden, so a new chip family can surface
          before a rule exists. Add a family to the config and rerun the scrape.
        </p>
        <label class="pf-field pf-unmapped-search">
          <span>Search unmapped certificates</span>
          <input type="search" placeholder="Certificate, source, vendor, or environment…" aria-label="Search unmapped certificates">
        </label>
        <div class="pf-unmapped-count-line small"></div>
        <div class="pf-unmapped-table-wrap">
          <table class="pf-unmapped-table">
            <thead><tr>
              <th>Certificate</th>
              <th>Entropy source</th>
              <th>Vendor</th>
              <th>Reuse</th>
              <th>Noise</th>
              <th>Entropy / output</th>
              <th>Operating environments</th>
            </tr></thead>
            <tbody></tbody>
          </table>
        </div>
      </div>
    </details>
  `;

  const stats = root.querySelector(".platform-stats");
  const callout = root.querySelector(".platform-callout");
  const list = root.querySelector(".pf-list");
  const count = root.querySelector(".pf-count");
  const search = root.querySelector(".pf-search input");
  const category = root.querySelector(".pf-category");
  const vendor = root.querySelector(".pf-vendor-select");
  const noise = root.querySelector(".pf-noise");
  const reuse = root.querySelector(".pf-reuse");
  const full = root.querySelector(".pf-full");
  const reset = root.querySelector(".pf-reset");
  const sort = root.querySelector(".pf-sort select");
  const download = root.querySelector(".pf-download");
  const unmappedDetails = root.querySelector(".pf-unmapped");
  const unmappedSearch = root.querySelector(".pf-unmapped-search input");
  const unmappedCountLine = root.querySelector(".pf-unmapped-count-line");
  const unmappedBody = root.querySelector(".pf-unmapped-table tbody");
  root.querySelector(".pf-unmapped-count").textContent = num.format(unmappedCount);

  stats.innerHTML = [
    ["Chipset families", platformFamilies.length, `${strongFamilies} with open + physical`],
    ["Certificates mapped", mappedCount, `of ${num.format(number(totalEsv))} ESV certificates`],
    ["Open + physical matches", strongMatches, "across families; overlaps allowed"],
    ["Unmapped certificates", unmappedCount, "no family match; inspect for new leads", "unmapped"]
  ].map(([label, value, hint, href]) => {
    const tag = href ? "a" : "div";
    const attrs = href ? ` href="#${href}"` : "";
    return `<${tag} class="stat${href ? " stat-link" : ""}"${attrs}>
      <div class="value">${num.format(value)}</div>
      <div class="label">${escapeHtml(label)}</div>
      <div class="hint">${escapeHtml(hint)}</div>
    </${tag}>`;
  }).join("");

  const top = platformFamilies
    .filter((family) => family.openPhysical > 0)
    .sort((a, b) => b.openPhysical - a.openPhysical || b.allCount - a.allCount)
    .slice(0, 4);

  callout.innerHTML = `
    <strong>Start here</strong>
    <span class="pf-top-links">${top.map((family) => (
      `<a class="pf-top-link" href="#family-${family.id}" data-open="${escapeHtml(family.id)}">${escapeHtml(family.family)} <b>${family.openPhysical}</b></a>`
    )).join("")}</span>
    <span class="pf-callout-note">${strongFamilies} ${plural(strongFamilies, "family", "families")} have at least one open + physical certificate; counts are certificate matches, not unique chips.</span>
  `;

  category.innerHTML = `<option value="all">All categories (${platformFamilies.length})</option>`
    + categories.map((name) => `<option value="${escapeHtml(name)}">${escapeHtml(name)}</option>`).join("");
  vendor.innerHTML = `<option value="all">All entropy vendors (${vendors.length})</option>`
    + vendors.map((name) => `<option value="${escapeHtml(name)}">${escapeHtml(name)}</option>`).join("");

  noise.value = state.noise;
  reuse.value = state.reuse;
  full.checked = state.fullEntropy;

  /* ---------- detail ---------- */

  function certLinkHtml(cert) {
    return cert.url
      ? `<a class="pf-cert-id" href="${escapeHtml(cert.url)}" target="_blank" rel="noopener">${escapeHtml(cert.cert)}</a>`
      : `<span class="pf-cert-id">${escapeHtml(cert.cert)}</span>`;
  }

  function reuseBadgeHtml(cert) {
    return cert.reuse_status === "Open for Reuse"
      ? `<span class="badge open">Open for Reuse</span>`
      : `<span class="badge restricted">${escapeHtml(cert.reuse_status || "Restricted")}</span>`;
  }

  function noiseBadgeHtml(cert) {
    return cert.noise_source
      ? `<span class="badge pf-badge-noise">${escapeHtml(cert.noise_source)}</span>`
      : "";
  }

  function entropySummary(cert) {
    return [
      cert.bits_per_output
        ? (/full/i.test(cert.bits_per_output)
          ? "Full entropy"
          : `${cert.bits_per_output} bits/output`)
        : "",
      cert.output_size_bits && `${cert.output_size_bits} bits output`
    ].filter(Boolean).join(" · ");
  }

  function certHtml(cert) {
    const certLink = certLinkHtml(cert);
    const reuseBadge = reuseBadgeHtml(cert);
    const noiseBadge = noiseBadgeHtml(cert);
    const entropy = entropySummary(cert);
    const environments = cert.environments
      .slice(0, 3)
      .map((environment) => `<span class="pf-env-chip" title="${escapeHtml(environment)}">${escapeHtml(shorten(environment, 56))}</span>`)
      .join("");
    const more = cert.environments.length > 3
      ? `<span class="pf-env-more">+${cert.environments.length - 3} more</span>`
      : "";
    const pud = cert.public_use_document_url
      ? `<a href="${escapeHtml(cert.public_use_document_url)}" target="_blank" rel="noopener">PUD</a>`
      : "";

    return `<article class="pf-cert${cert.strong ? " is-strong" : ""}">
      <div class="pf-cert-top">
        ${certLink}
        <span class="pf-impl">${escapeHtml(cert.implementation)}</span>
        ${reuseBadge}
        ${noiseBadge}
      </div>
      <div class="pf-cert-meta">
        <span>${escapeHtml(cert.vendor)}</span>
        ${entropy ? `<span>${escapeHtml(entropy)}</span>` : ""}
        <span>Validated ${escapeHtml(cert.validated || "—")}</span>
        ${pud}
      </div>
      <div class="pf-envs">${environments}${more}</div>
    </article>`;
  }

  function detailHtml(family) {
    const isShortlist = state.vendor === "all" && state.noise === "Physical"
      && state.reuse === "Open for Reuse" && !state.fullEntropy;
    const isAll = state.vendor === "all" && state.noise === "all"
      && state.reuse === "all" && !state.fullEntropy;
    const total = family.allCount;
    let summary;
    if (isShortlist) {
      summary = `<strong>${family.openPhysical} of ${total}</strong> ${plural(total, "certificate")} ${family.openPhysical === 1 ? "is" : "are"} open for reuse and physical.`;
    } else if (isAll) {
      summary = `Showing all <strong>${family.certs.length}</strong> ${plural(family.certs.length, "certificate")} for this family.`;
    } else {
      summary = `<strong>${family.certs.length} of ${total}</strong> ${plural(total, "certificate")} match the current entropy filters; ${family.openPhysical} ${family.openPhysical === 1 ? "is" : "are"} open + physical.`;
    }
    const environments = family.environments.length
      ? `<details class="pf-env-detail">
          <summary>Show all ${family.environments.length} matching ${plural(family.environments.length, "environment")}</summary>
          <ul>${family.environments.map((environment) => `<li>${escapeHtml(environment)}</li>`).join("")}</ul>
        </details>`
      : "";

    return `<div class="pf-detail-head">
        <p>${summary}</p>
        <p class="pf-detail-meta">${family.open} open · ${family.physical} physical · ${family.entropyVendors.length} entropy ${plural(family.entropyVendors.length, "vendor")} · ${family.certs.length} matching ESV ${plural(family.certs.length, "certificate")}</p>
      </div>
      <div class="pf-certs">${family.certs.map(certHtml).join("")}</div>
      ${environments}`;
  }

  function unmappedEnvironmentsHtml(cert) {
    if (cert.environments.length === 0) return "—";
    if (cert.environments.length === 1) {
      return escapeHtml(shorten(cert.environments[0], 100));
    }
    return `<details class="pf-unmapped-envs">
      <summary>${cert.environments.length} environments</summary>
      <ul>${cert.environments.map((environment) => `<li>${escapeHtml(environment)}</li>`).join("")}</ul>
    </details>`;
  }

  function unmappedRowHtml(cert) {
    const entropy = entropySummary(cert);
    return `<tr${cert.strong ? ' class="is-strong"' : ""}>
      <td>${certLinkHtml(cert)}</td>
      <td>${escapeHtml(cert.implementation)}</td>
      <td>${escapeHtml(cert.vendor)}</td>
      <td>${reuseBadgeHtml(cert)}</td>
      <td>${noiseBadgeHtml(cert)}</td>
      <td>${entropy ? escapeHtml(entropy) : "—"}</td>
      <td>${unmappedEnvironmentsHtml(cert)}</td>
    </tr>`;
  }

  function renderUnmapped() {
    const query = unmappedSearch.value.trim().toLowerCase();
    const matches = unmappedCerts.filter((cert) => [
      cert.cert,
      cert.implementation,
      cert.vendor,
      cert.reuse_status,
      cert.noise_source,
      ...cert.environments
    ].join("\n").toLowerCase().includes(query));

    unmappedCountLine.textContent = `${num.format(matches.length)} of ${num.format(unmappedCount)} unmapped ${plural(unmappedCount, "certificate")}`;
    unmappedBody.innerHTML = matches.length
      ? matches.map(unmappedRowHtml).join("")
      : `<tr><td colspan="7" class="pf-unmapped-empty">No unmapped certificates match.</td></tr>`;
  }

  function familyHtml(family) {    const examples = family.examples.length
      ? family.examples.map((environment) => escapeHtml(shorten(environment, 42))).join(" · ")
      : "No matching environments";
    return `<details class="pf-family" id="family-${family.id}" data-id="${escapeHtml(family.id)}"${state.open.has(family.id) ? " open" : ""}>
      <summary class="pf-summary">
        <span class="pf-identity">
          <span class="pf-name">${escapeHtml(family.family)}</span>
          <span class="pf-platform-vendor">${escapeHtml(family.platform_vendor)}</span>
          <span class="pf-cat">${escapeHtml(family.category)}</span>
        </span>
        <span class="pf-metric pf-open ${family.openPhysical > 0 ? "is-strong" : "is-zero"}">
          <strong>${family.openPhysical}</strong><span class="pf-metric-label">open + physical</span>
        </span>
        <span class="pf-metric">
          <strong>${family.certs.length}</strong>${family.certs.length !== family.allCount ? `<span class="pf-of">of ${family.allCount}</span>` : ""}<span class="pf-metric-label">ESV certs</span>
        </span>
        <span class="pf-metric">
          <strong>${family.entropyVendors.length}</strong><span class="pf-metric-label">entropy vendors</span>
        </span>
        <span class="pf-examples" title="${escapeHtml(family.examples.join(" · "))}">${examples}</span>
        <span class="pf-chevron" aria-hidden="true">▸</span>
      </summary>
      <div class="pf-detail">${detailHtml(family)}</div>
    </details>`;
  }

  function renderList() {
    const result = filteredFamilies();
    const totalCerts = new Set(result.flatMap((family) => family.certs.map((cert) => cert.cert))).size;
    count.textContent = `${result.length} ${plural(result.length, "family", "families")} · ${totalCerts} unique ${plural(totalCerts, "certificate")}`;

    list.innerHTML = result.length
      ? result.map(familyHtml).join("")
      : `<div class="pf-empty">No families match. <button type="button" class="pf-reset-view">Reset view</button></div>`;

    for (const details of list.querySelectorAll("details.pf-family")) {
      details.addEventListener("toggle", () => {
        if (details.open) state.open.add(details.dataset.id);
        else state.open.delete(details.dataset.id);
      });
    }

    const resetView = list.querySelector(".pf-reset-view");
    if (resetView) {
      resetView.addEventListener("click", () => {
        state.query = "";
        state.category = "all";
        search.value = "";
        category.value = "all";
        resetEntropy();
        renderList();
      });
    }
  }

  function resetEntropy() {
    state.vendor = "all";
    state.noise = "Physical";
    state.reuse = "Open for Reuse";
    state.fullEntropy = false;
    vendor.value = "all";
    noise.value = "Physical";
    reuse.value = "Open for Reuse";
    full.checked = false;
  }

  /* ---------- events ---------- */

  search.addEventListener("input", () => {
    state.query = search.value;
    renderList();
  });
  category.addEventListener("change", () => {
    state.category = category.value;
    renderList();
  });
  vendor.addEventListener("change", () => {
    state.vendor = vendor.value;
    renderList();
  });
  noise.addEventListener("change", () => {
    state.noise = noise.value;
    renderList();
  });
  reuse.addEventListener("change", () => {
    state.reuse = reuse.value;
    renderList();
  });
  full.addEventListener("change", () => {
    state.fullEntropy = full.checked;
    renderList();
  });
  reset.addEventListener("click", () => {
    resetEntropy();
    renderList();
  });
  sort.addEventListener("change", () => {
    state.sortKey = sort.value;
    state.sortDir = sort.value === "name" ? 1 : -1;
    renderList();
  });
  unmappedSearch.addEventListener("input", renderUnmapped);

  for (const link of callout.querySelectorAll("[data-open]")) {
    link.addEventListener("click", (event) => {
      event.preventDefault();
      const id = link.dataset.open;
      state.query = "";
      state.category = "all";
      search.value = "";
      category.value = "all";
      resetEntropy();
      state.open.add(id);
      renderList();
      requestAnimationFrame(() => {
        const family = document.getElementById(`family-${id}`);
        if (!family) return;
        family.open = true;
        family.scrollIntoView({behavior: "smooth", block: "center"});
      });
    });
  }

  download.addEventListener("click", () => {
    const result = filteredFamilies();
    const header = [
      "family", "platform_vendor", "category", "open_physical",
      "matching_esv_certs", "all_esv_certs", "open", "physical",
      "entropy_vendors", "example_environments", "certificates"
    ];
    const lines = [header.join(",")].concat(result.map((family) => [
      family.family,
      family.platform_vendor,
      family.category,
      family.openPhysical,
      family.certs.length,
      family.allCount,
      family.open,
      family.physical,
      family.entropyVendors.length,
      family.examples.join(" | "),
      family.certs.map((cert) => cert.cert).join(" ")
    ].map(csvCell).join(",")));
    const blob = new Blob([lines.join("\n")], {type: "text/csv"});
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = "platform-shortlist.csv";
    document.body.append(link);
    link.click();
    link.remove();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  });

  renderList();
  renderUnmapped();

  const unmappedLink = stats.querySelector('a[href="#unmapped"]');
  if (unmappedLink) {
    unmappedLink.addEventListener("click", () => {
      unmappedDetails.open = true;
    });
  }
  if (window.location.hash === "#unmapped") unmappedDetails.open = true;

  return root;
}
